ExportResult Export(const std::string& outputDir, const DMGameEngine::Scene& editScene) {
    ExportResult result;
    namespace fs = std::filesystem;
    std::error_code ec;

    const fs::path out = fs::path(outputDir).lexically_normal();
    if (out.empty()) { result.Error = "empty output directory"; return result; }

    fs::create_directories(out / "assets/scene", ec);
    fs::create_directories(out / "assets/models", ec);
    fs::create_directories(out / "src", ec);
    if (ec) { result.Error = "cannot create output directories: " + ec.message(); return result; }

    // 1. Scene dump (always the EDIT state; the caller guarantees it).
    const std::string sceneRel = "assets/scene/main.scene";
    DMGameEngine::SceneSerializer::Save(editScene, (out / sceneRel).string());

    // 2. Asset registry snapshot (UUID -> original path metadata; used by the
    // generated main.cpp to re-bind copied model files by UUID).
    AssetManager::Get().SaveRegistry((out / "assets/registry.json").string());

    // 3. Copy model files referenced by the scene (UUID -> path via AssetManager).
    std::unordered_set<DMGameEngine::AssetUUID> copied;
    std::set<std::string> copiedFilenames;
    editScene.GetRegistry().view<MeshComponent>().each([&](auto, const MeshComponent& mc) {
        if (!mc.MeshAsset.IsValid()) {
            if (mc.Mesh)
                result.ProceduralMeshes++;   // K-012: procedural meshes do not survive serialization
            return;
        }
        if (copied.count(mc.MeshAsset.GetUUID()))
            return;
        const auto* meta = AssetManager::Get().GetMetadata(mc.MeshAsset.GetUUID());
        if (!meta || meta->Path.empty())
            return;
        const fs::path srcPath = meta->Path;
        if (!fs::exists(srcPath, ec))
            return;   // dangling registry entry; runtime will warn
        fs::path dst = out / "assets/models" / srcPath.filename();
        if (!copiedFilenames.insert(srcPath.filename().string()).second)
            return;   // same filename from a different directory: first one wins, runtime dedupes by path
        fs::copy_file(srcPath, dst, fs::copy_options::overwrite_existing, ec);
        if (ec) {
            DMGE_CLIENT_WARN("Export: failed to copy model '{0}': {1}", srcPath.string(), ec.message());
            ec.clear();
            return;
        }
        copied.insert(mc.MeshAsset.GetUUID());
        result.ModelsCopied++;
    });

    // 4. Engine shaders -> <out>/shaders (relative shader paths in the game).
    std::string err;
    if (!CopyDirectoryTree(kEngineShaderDir, out / "shaders", err)) {
        result.Error = "shader copy failed: " + err;
        return result;
    }

    // 5. Project template.
    WriteTextFile(out / "CMakeLists.txt", GeneratedCMakeLists());
    WriteTextFile(out / "src" / "main.cpp", GeneratedMainCpp());
    WriteTextFile(out / "README.md", GeneratedReadme(sceneRel));

    result.OutputDir = out.string();
    result.Ok = true;
    return result;
}

