bool CopyDirectoryTree(const fs::path& src, const fs::path& dst, std::string& error) {
    std::error_code ec;
    if (!fs::exists(src, ec)) {
        error = "source directory missing: " + src.string();
        return false;
    }
    fs::create_directories(dst, ec);
    for (auto& it : fs::recursive_directory_iterator(src, ec)) {
        if (ec) break;
        const auto rel = fs::relative(it.path(), src, ec);
        const auto target = dst / rel;
        if (it.is_directory(ec)) {
            fs::create_directories(target, ec);
        } else if (it.is_regular_file(ec)) {
            fs::create_directories(target.parent_path(), ec);
            fs::copy_file(it.path(), target, fs::copy_options::overwrite_existing, ec);
            if (ec) { error = "copy failed: " + it.path().string(); return false; }
        }
    }
    return true;
}

